// 调休上班日（周末但按工作日对待）
const MAKEUP_WORKDAYS = {
  2025: ['2025-01-26', '2025-02-08', '2025-04-27', '2025-09-28', '2025-10-11'],
  2026: ['2026-02-15', '2026-02-28', '2026-05-09', '2026-10-10'],
}

const toSet = (obj) => new Set(Object.values(obj).flat())

/**
 * 构造日历。custom 来自库表，优先级高于内置：
 *   holiday 覆盖：出现在 holidays 即休；workday 覆盖：出现在 workdays 即上班（可调休抵消内置假日）。
 * @param {{holidays?: string[], workdays?: string[]}} custom
 */
export function buildCalendar(custom = {}) {
  const holidays = toSet(HOLIDAYS)
  const workdays = toSet(MAKEUP_WORKDAYS)
  for (const d of custom.holidays || []) holidays.add(d)
  for (const d of custom.workdays || []) {
    workdays.add(d)
    holidays.delete(d)
  }
  return {
    holidays,
    workdays,
    isWeekend(dateStr) {
      const day = new Date(`${dateStr}T00:00:00Z`).getUTCDay()
      return day === 0 || day === 6
    },
    // 法定口径：休息日（周末）+ 法定休假日 − 调休上班日
    isLegalNonWorking(dateStr) {
      if (workdays.has(dateStr)) return false
      return holidays.has(dateStr) || this.isWeekend(dateStr)
    },
    // 工作日口径：只认周一到周五（不剔除法定假日）
    isWeekday(dateStr) {
      return !this.isWeekend(dateStr)
    },
  }
}

